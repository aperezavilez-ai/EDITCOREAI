"use strict";

/**
 * Audit / repair / purge of EditCoreAI brain installed repos.
 * Creates wrapper SKILL.md for salvageable packages; deletes dead entries.
 */

const fs = require("node:fs");
const path = require("node:path");
const { EditCoreBrainService } = require("../brain-service");

const FORCE_PURGE_IDS = new Set([
  "asgeirtj-system-prompts-leaks", // leaked prompts — not a legitimate skill
]);

function readTextSafe(filePath, max = 12_000) {
  try {
    if (!fs.existsSync(filePath)) return "";
    return fs.readFileSync(filePath, "utf8").slice(0, max);
  } catch {
    return "";
  }
}

function packageMeta(installPath) {
  try {
    const pkg = JSON.parse(fs.readFileSync(path.join(installPath, "package.json"), "utf8"));
    return {
      name: pkg.name || "",
      description: pkg.description || "",
      version: pkg.version || "",
      keywords: Array.isArray(pkg.keywords) ? pkg.keywords.slice(0, 12) : [],
    };
  } catch {
    return null;
  }
}

function skillSlug(item) {
  return String(item.name || item.id || "repo")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 64) || "repo-skill";
}

function buildWrapperSkillMd(item, { pkg, readmeHead }) {
  const slug = skillSlug(item);
  const title = item.name || item.id;
  const description = (pkg?.description || `Guide for using ${title} inside EditCoreAI agent workflows.`).replace(/\r?\n/g, " ").slice(0, 280);
  const keywords = (pkg?.keywords || []).join(", ");
  const url = item.url || "";
  return `---
name: ${slug}
description: ${JSON.stringify(description)}
---

# ${title}

Agent skill wrapper generated by EDITCOREAI so this installed repository is usable as a brain skill.

## When to use
- The user asks about **${title}** or related APIs/tools.
- You need integration guidance, setup steps, or API patterns from this package/repo.

## Source
- Repo: ${url || title}
- Installed path: \`${String(item.installedPath || "").replace(/\\\\/g, "/")}\`
${pkg?.version ? `- Package version: ${pkg.version}` : ""}
${keywords ? `- Keywords: ${keywords}` : ""}

## Instructions for the agent
1. Prefer reading files inside the installed path with project tools before inventing APIs.
2. Summarize only verified facts from README / package docs.
3. Do not claim the package is installed in the user workspace unless \`package.json\` / imports prove it.
4. For SDKs: show minimal authenticated client usage, error handling, and env var names without inventing secrets.
5. For MCP servers: explain how to wire allowlisted MCP tools; never start unauthorized remote processes.

## README excerpt
\`\`\`
${(readmeHead || "(no README found)").slice(0, 3500)}
\`\`\`
`;
}

function isSalvageable(item, installPath) {
  if (FORCE_PURGE_IDS.has(item.id)) return false;
  if (!installPath || !fs.existsSync(installPath)) return false;
  const entries = fs.readdirSync(installPath).filter((n) => !n.startsWith(".git"));
  if (!entries.length) return false;
  const hasDocs = ["README.md", "readme.md", "README", "package.json", "pyproject.toml", "Cargo.toml", "go.mod"]
    .some((n) => fs.existsSync(path.join(installPath, n)));
  return hasDocs || entries.length >= 3;
}

function normalizeSkillPath(filePath, installPath) {
  const rel = path.relative(installPath, filePath).replace(/\\/g, "/");
  return rel && !rel.startsWith("..") ? rel : "";
}

async function healAndPurgeBrainSkills({
  userDataPath = path.join(process.env.APPDATA || "", "EDITCOREAI"),
  catalogPath = path.join(__dirname, "..", "brain-seed", "catalog.json"),
  sharedSkillPaths = [path.join(__dirname, "..", "brain-seed", "skills")],
  dryRun = false,
} = {}) {
  const previousDebug = console.debug;
  console.debug = () => undefined;

  const brain = new EditCoreBrainService({ catalogPath, userDataPath, sharedSkillPaths });
  const before = await brain.auditTools("", { repair: false });
  const manifest = await brain.readGlobalManifest();

  const repaired = [];
  const purged = [];
  const keptActive = [];
  const nextItems = [];

  for (const item of manifest.items) {
    const installPath = String(item.installedPath || "");
    const audit = await brain.auditInstalledItem(item, "global");
    if (audit.status === "active" && audit.skillCount > 0) {
      const discovered = await brain.discoverItemSkills(item);
      const skills = discovered.flatMap((skill) => {
        const rel = normalizeSkillPath(skill.filePath, installPath);
        if (!skill.name || !rel) return [];
        return [{ name: skill.name, description: skill.description || `${item.name}.`, source: skill.source || "brain", relativePath: rel }];
      });
      nextItems.push({
        ...item,
        status: "active",
        disabled: false,
        active: true,
        auditReason: audit.reason,
        lastAuditedAt: new Date().toISOString(),
        skills: skills.length ? skills : (item.skills || []),
      });
      keptActive.push(item.id);
      continue;
    }

    if (isSalvageable(item, installPath)) {
      const pkg = packageMeta(installPath);
      const readmeHead = readTextSafe(path.join(installPath, "README.md"))
        || readTextSafe(path.join(installPath, "readme.md"))
        || readTextSafe(path.join(installPath, "README"));
      const skillMd = buildWrapperSkillMd(item, { pkg, readmeHead });
      const skillPath = path.join(installPath, "SKILL.md");
      if (!dryRun) fs.writeFileSync(skillPath, skillMd, "utf8");

      const slug = skillSlug(item);
      const description = (pkg?.description || `Guide for ${item.name}`).slice(0, 280);
      const healed = {
        ...item,
        status: "active",
        disabled: false,
        active: true,
        detectedType: "codex-skill",
        detectedFiles: Array.from(new Set([...(item.detectedFiles || []), "SKILL.md", "README.md", "package.json"].filter(Boolean))),
        auditReason: "Wrapper SKILL.md generated by skill healer",
        lastAuditedAt: new Date().toISOString(),
        lastRepairedAt: new Date().toISOString(),
        skills: [{
          name: slug,
          description,
          source: "brain",
          relativePath: "SKILL.md",
        }],
      };
      nextItems.push(healed);
      repaired.push({ id: item.id, name: item.name, skill: slug });
      continue;
    }

    // Purge
    purged.push({ id: item.id, name: item.name, reason: FORCE_PURGE_IDS.has(item.id) ? "forced-purge" : (!fs.existsSync(installPath) ? "missing-path" : "unsalvageable") });
    if (!dryRun && installPath && fs.existsSync(installPath)) {
      try {
        fs.rmSync(installPath, { recursive: true, force: true });
      } catch {
        /* best effort */
      }
    }
  }

  if (!dryRun) await brain.writeGlobalManifest(nextItems);

  const after = await brain.auditTools("", { repair: false });
  console.debug = previousDebug;

  const report = {
    before: {
      total: before.installed.length,
      active: before.activeInstalledCount,
      invalid: before.invalidInstalledCount,
    },
    repaired,
    purged,
    keptActive,
    after: {
      total: after.installed.length,
      active: after.activeInstalledCount,
      invalid: after.invalidInstalledCount,
      disabled: after.disabledInstalledCount,
    },
    allActive: after.invalidInstalledCount === 0 && after.installed.every((a) => a.status === "active"),
  };
  return report;
}

module.exports = {
  healAndPurgeBrainSkills,
  buildWrapperSkillMd,
  isSalvageable,
  FORCE_PURGE_IDS,
};
