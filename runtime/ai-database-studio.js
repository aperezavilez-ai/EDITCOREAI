"use strict";

const path = require("path");
const fs = require("fs");

class AIDatabaseStudio {
  constructor(options = {}) {
    this.projectRoot = options.projectRoot || process.cwd();
    this.migrationsDir = path.join(this.projectRoot, "supabase", "migrations");
  }

  /**
   * Genera un archivo de migración SQL basado en una descripción en lenguaje natural
   */
  generateMigration({ name = "create_table", description = "", tables = [] } = {}) {
    const timestamp = new Date().toISOString().replace(/[-:T]/g, "").slice(0, 14);
    const fileName = `${timestamp}_${name.toLowerCase().replace(/[^a-z0-9_]/g, "_")}.sql`;
    
    if (!fs.existsSync(this.migrationsDir)) {
      fs.mkdirSync(this.migrationsDir, { recursive: true });
    }

    const sqlLines = [
      `-- Migration: ${name}`,
      `-- Description: ${description || "Auto-generated by EditCoreAI Database Studio"}`,
      `-- Generated at: ${new Date().toISOString()}`,
      "",
    ];

    for (const table of tables) {
      const tableName = table.name || "items";
      sqlLines.push(`CREATE TABLE IF NOT EXISTS public.${tableName} (`);
      sqlLines.push(`  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),`);
      sqlLines.push(`  created_at TIMESTAMPTZ DEFAULT now() NOT NULL,`);
      sqlLines.push(`  updated_at TIMESTAMPTZ DEFAULT now() NOT NULL,`);

      if (Array.isArray(table.columns)) {
        for (const col of table.columns) {
          const colType = col.type || "TEXT";
          const nullable = col.nullable ? "" : " NOT NULL";
          const unique = col.unique ? " UNIQUE" : "";
          const ref = col.references ? ` REFERENCES public.${col.references}(id) ON DELETE CASCADE` : "";
          sqlLines.push(`  ${col.name} ${colType}${nullable}${unique}${ref},`);
        }
      }

      sqlLines.push(`);`);
      sqlLines.push("");
      sqlLines.push(`-- Enable Row Level Security (RLS)`);
      sqlLines.push(`ALTER TABLE public.${tableName} ENABLE ROW LEVEL SECURITY;`);
      sqlLines.push("");
    }

    const fullSql = sqlLines.join("\n");
    const targetFile = path.join(this.migrationsDir, fileName);
    fs.writeFileSync(targetFile, fullSql, "utf8");

    return {
      ok: true,
      fileName,
      filePath: targetFile,
      sql: fullSql,
    };
  }

  /**
   * Genera tipos estrictos de TypeScript a partir de las tablas
   */
  generateTypeScriptTypes(tables = []) {
    const lines = [
      "export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];",
      "",
      "export interface Database {",
      "  public: {",
      "    Tables: {",
    ];

    for (const table of tables) {
      const tName = table.name || "items";
      lines.push(`      ${tName}: {`);
      lines.push(`        Row: {`);
      lines.push(`          id: string;`);
      lines.push(`          created_at: string;`);
      lines.push(`          updated_at: string;`);

      if (Array.isArray(table.columns)) {
        for (const col of table.columns) {
          const tsType = this._mapSqlToTs(col.type);
          lines.push(`          ${col.name}: ${tsType}${col.nullable ? " | null" : ""};`);
        }
      }

      lines.push(`        };`);
      lines.push(`      };`);
    }

    lines.push("    };");
    lines.push("  };");
    lines.push("}");

    return lines.join("\n");
  }

  _mapSqlToTs(sqlType = "") {
    const s = String(sqlType).toUpperCase();
    if (s.includes("INT") || s.includes("NUMERIC") || s.includes("FLOAT") || s.includes("DECIMAL")) return "number";
    if (s.includes("BOOL")) return "boolean";
    if (s.includes("JSON")) return "Json";
    return "string";
  }

  listMigrations() {
    if (!fs.existsSync(this.migrationsDir)) return [];
    return fs.readdirSync(this.migrationsDir).filter((f) => f.endsWith(".sql"));
  }
}

module.exports = {
  AIDatabaseStudio,
};
